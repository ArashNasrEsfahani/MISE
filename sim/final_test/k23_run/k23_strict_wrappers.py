def render(target: str, root: str = HERE) -> str:
    src, edits = EDITS[target]
    text = open(os.path.join(root, *src.split("/")), encoding="utf-8", newline="").read()
    for old, new in edits:
        n = text.count(old)
        if n != 1:
            raise ValueError(f"{target}: an edit's original text occurs {n} times in {src} (the original changed: regenerate + review)")
        text = text.replace(old, new)
    return text


def check(root: str = HERE) -> list:
    why = []
    for t in EDITS:
        try:
            want = render(t, root)
        except (OSError, ValueError) as e:
            why.append(f"{t}: {e}")
            continue
        try:
            got = open(os.path.join(root, *t.split("/")), encoding="utf-8", newline="").read()
        except OSError:
            why.append(f"{t}: missing")
            continue
        if got != want:
            why.append(f"{t}: differs from its rendered original (regenerate with --write, then review)")
    return why


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="K23 strict wrappers (generated from the originals)")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)
    if a.write:
        for t in EDITS:
            with open(os.path.join(HERE, *t.split("/")), "w", encoding="utf-8", newline="\n") as f:
                f.write(render(t))
            print("wrote", t)
    why = check()
    print("strict wrappers: " + ("OK" if not why else "; ".join(why)))
    return 0 if not why else 1


if __name__ == "__main__":
    sys.exit(main())
